/**
 * Fetch up to `count` sample passages for the "From the book" section.
 *
 * The /read endpoint shape varies by book type:
 *   - explicit `chunks[]` (if the API ever returns them),
 *   - `paragraphs[]` for reassembled regular books,
 *   - `chapters[].content` for AI-written books.
 * We coalesce whichever is present into leading SamplePassage objects.
 * Returns [] on any failure (catalog stubs / no content / API down).
 */
// Gutenberg / scan boilerplate that makes a useless "sample passage" if it
// leaks past the front-matter skip below.
const FRONT_MATTER_RE =
  /transcriber|project\s+gutenberg|gutenberg-tm|produced\s+by|distributed\s+proofread|all\s+rights\s+reserved|electronic\s+edition/i;

// Chunk/line splitting often cuts mid-sentence, so a sampled paragraph can open
// on a lowercase fragment ("…electrised that is foul. EXPERIMENT VI…"). Drop the
// leading partial sentence so the passage starts at a real boundary; if there's
// no clean break (or it would leave too little), keep the original.
function trimToSentenceStart(text: string): string {
  if (/^["“'([A-Z0-9]/.test(text)) return text; // already starts a sentence/quote/number
  const m = text.match(/[.?!]\s+(["“'(]?[A-Z])/);
  if (m && m.index !== undefined) {
    const rest = text.slice(m.index + m[0].length - m[1].length).trim();
    if (rest.length >= 60) return rest;
  }
  return text;
}

export async function getSamplePassages(
  id: string,
  count = 3,
): Promise<SamplePassage[]> {
  let res: ReadResponse | null = null;
  try {
    // Public, edge-cached read endpoint (serves ready books without auth).
    // The authed /api/agents/{id}/read is gated for the in-app reader, so the
    // SSR (no user cookie) must use the public mirror or it 401s and renders
    // a passage-less — and thus thin — book page.
    res = await get<ReadResponse>(
      `/api/public/book/${encodeURIComponent(id)}/read`,
    );
  } catch {
    return [];
  }
  if (!res) return [];

  const out: SamplePassage[] = [];

  if (Array.isArray(res.chunks) && res.chunks.length) {
    for (const c of res.chunks) {
      const text = (c.text || "").trim();
      if (text) out.push({ index: out.length, text });
      if (out.length >= count) break;
    }
    return out;
  }

  if (Array.isArray(res.paragraphs) && res.paragraphs.length) {
    const paras = res.paragraphs;
    // Skip front matter (transcriber's notes, title page, contents) — for a long
    // book the opening paragraphs are boilerplate that makes a poor, non-
    // representative sample. Start ~10% in, require real prose length, and drop
    // Gutenberg boilerplate; fall back to any substantive paragraph if empty.
    const start = Math.min(
      Math.floor(paras.length * 0.1),
      Math.max(paras.length - count, 0),
    );
    const pick = (from: number, minLen: number) => {
      for (let i = from; i < paras.length && out.length < count; i++) {
        const raw = (paras[i] || "").trim();
        if (raw.length < minLen) continue;
        if (FRONT_MATTER_RE.test(raw)) continue;
        out.push({ index: out.length, text: trimToSentenceStart(raw) });
      }
    };
    pick(start, 100);
    if (!out.length) pick(0, 40);
    return out;
  }

  if (Array.isArray(res.chapters) && res.chapters.length) {
    for (const ch of res.chapters) {
      const body = (ch.content || "").trim();
      if (!body) continue;
      // First paragraph of the chapter as a representative passage.
      const firstPara = body.split(/\n\n+/)[0]?.trim() || body;
      out.push({ index: out.length, text: firstPara });
      if (out.length >= count) break;
    }
  }

  return out;
}

