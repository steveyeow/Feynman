export interface BookData {
  agent: AgentRow;
  meta: AgentMeta;
  title: string;
  author: string;
  subtitle: string;
  description: string;
  category: string;
  chapters: Chapter[];
  totalWords: number;
}

/** Resolve the display author the way the legacy `_resolve_og_author` does. */
function resolveAuthor(agent: AgentRow): string {
  const meta = agent.meta || {};
  return (meta.author || agent.source || "").toString().trim();
}

/**
 * Fetch the agent row and normalize the book view-model. Returns null when
 * the agent is missing or the API is unreachable — callers should
 * notFound() on null.
 */
export async function getBookData(id: string): Promise<BookData | null> {
  let agent: AgentRow | null = null;
  try {
    agent = await get<AgentRow>(`/api/agents/${encodeURIComponent(id)}`);
  } catch {
    return null;
  }
  if (!agent || !agent.id) return null;

  const meta: AgentMeta = agent.meta || {};
  const outline = meta.outline || null;
  const subtitle = (outline?.subtitle || "").toString();
  const chapters = Array.isArray(outline?.chapters) ? outline!.chapters! : [];
  const title = (meta.title || agent.name || "Untitled").toString();
  const author = resolveAuthor(agent);
  let totalWords = Number(meta.total_words || 0);
  if (!totalWords && meta.chunk_count) {
    totalWords = Number(meta.chunk_count) * WORDS_PER_CHUNK;
  }

  return {
    agent,
    meta,
    title,
    author,
    subtitle,
    description: (meta.description || "").toString(),
    category: (meta.category || "").toString().trim(),
    chapters,
    totalWords,
  };
}

