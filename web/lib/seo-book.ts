/**
 * Schema.org/Book — omits numberOfPages (we have no physical pages);
 * chapter structure goes in hasPart. Result is run through dropNulls for
 * parity with the Python jsonld_script wrapper.
 */
export function bookJsonld(args: BookJsonldArgs): Json {
  const out: Json = {
    "@context": "https://schema.org",
    "@type": "Book",
    name: args.title,
    description: args.description,
    url: args.url,
    image: args.image,
    inLanguage: args.inLanguage || "en",
    publisher: { "@type": "Organization", name: "Feynman", url: args.siteUrl },
  };
  if (args.author) out.author = { "@type": "Person", name: args.author };
  if (args.wordCount) out.wordCount = args.wordCount;
  if (args.chapters && args.chapters.length) {
    out.hasPart = args.chapters.map((c, i) => ({
      "@type": "Chapter",
      name: c.title || "",
      position: i + 1,
    }));
  }
  if (args.datePublished) out.datePublished = args.datePublished;
  if (args.dateModified) out.dateModified = args.dateModified;
  return dropNulls(out);
}

export interface QaPageJsonldArgs {
  question: string;
  answer: string;
  url: string;
  bookTitle: string;
  bookUrl: string;
  siteUrl?: string;
  dateCreated?: string;
}

/**
 * Schema.org/QAPage with all Google-required fields (name, text,
 * answerCount, acceptedAnswer). Falls back to a chat-deflection answer when
 * no synthesized answer is available (non-empty is required).
 */
export function qaPageJsonld(args: QaPageJsonldArgs): Json {
  let answerText = (args.answer || "").trim();
  if (!answerText) {
    answerText = `Open Feynman to chat with the book "${args.bookTitle}" and explore the answer in depth: ${args.bookUrl}`;
  }
  const author: Json = { "@type": "Organization", name: "Feynman" };
  if (args.siteUrl) author.url = args.siteUrl;

  const questionObj: Json = {
    "@type": "Question",
    name: args.question,
    text: args.question,
    answerCount: 1,
    upvoteCount: 0,
    url: args.url,
    author,
    acceptedAnswer: {
      "@type": "Answer",
      text: answerText,
      upvoteCount: 0,
      url: args.url,
      author,
    },
  };
  if (args.dateCreated) {
    questionObj.dateCreated = args.dateCreated;
    (questionObj.acceptedAnswer as Json).dateCreated = args.dateCreated;
  }
  return dropNulls({
    "@context": "https://schema.org",
    "@type": "QAPage",
    mainEntity: questionObj,
  });
}

