/**
 * Truncate to maxChars on a word boundary with an ellipsis (port of the
 * rsplit(" ", 1) pattern used across seo.py renderers).
 */
export function truncateWords(text: string, maxChars: number): string {
  const t = (text || "").trim();
  if (t.length <= maxChars) return t;
  const cut = t.slice(0, maxChars);
  const lastSpace = cut.lastIndexOf(" ");
  return (lastSpace > 0 ? cut.slice(0, lastSpace) : cut) + "…";
}

/** Clamp a meta description to ~200 chars on a word boundary. */
export function clampDescription(text: string, maxChars = 200): string {
  const t = (text || "").trim();
  if (t.length <= maxChars) return t;
  const cut = t.slice(0, maxChars - 3);
  const lastSpace = cut.lastIndexOf(" ");
  return (lastSpace > 0 ? cut.slice(0, lastSpace) : cut) + "...";
}

/** Reading-time + chapter stats line (port of render_stats math). */
export function statsLine(totalWords: number, chapterCount: number): string {
  const bits: string[] = [];
  if (totalWords) {
    bits.push(`${totalWords.toLocaleString("en-US")} words`);
    bits.push(`~${Math.max(1, Math.floor(totalWords / 250))} min read`);
  }
  if (chapterCount) {
    bits.push(`${chapterCount} chapters`);
  }
  return bits.join(" · ");
}

/**
 * The canonical reader/chat URL for a book. Real Next path, no hash —
 * the new app routes /read/{id} (not the legacy SPA's /#/read/{id}).
 */
export function readerUrl(id: string): string {
  return `${SITE_URL}/read/${encodeURIComponent(id)}`;
}
