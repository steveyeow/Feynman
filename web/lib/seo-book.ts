// ─── Capability detection (ported from seo.py detect_capabilities) ─────
//
// The Python original reads the `ai_books` row (total_words, outline,
// status). The JSON API only exposes the `agents` row, so this adapter
// works off agent.meta — which carries `outline`, `total_words`, and
// `chunk_count` for indexed books — and estimates word count from
// chunk_count (~250 words/chunk) when total_words is absent.

const READ_MIN_WORDS = 500;
const WORDS_PER_CHUNK = 250; // matches the index chunker's target size

export interface Capabilities {
  read: boolean;
  preview: boolean;
  chat: boolean;
}

export interface AgentMeta {
  author?: string;
  subtitle?: string;
  title?: string;
  description?: string;
  category?: string;
  chunk_count?: number;
  total_words?: number;
  outline?: { subtitle?: string; chapters?: Chapter[] } | null;
  status?: string;
  questions?: string[];
  [k: string]: unknown;
}

export interface AgentRow {
  id: string;
  name: string;
  type?: string;
  status?: string;
  source?: string;
  created_at?: string;
  meta?: AgentMeta;
}

/**
 * Decide which CTAs this book legitimately supports. Returns {read,
 * preview, chat}. Mirrors detect_capabilities but sourced from the agent
 * row (the only data the JSON API exposes for SSR).
 */
export function detectCapabilities(agent: AgentRow | null): Capabilities {
  if (!agent) return { read: false, preview: false, chat: false };
  const status = (agent.status || "").toLowerCase();
  if (["failed", "cancelled", "error"].includes(status)) {
    return { read: false, preview: false, chat: false };
  }

  const meta = agent.meta || {};
  const outline = meta.outline || null;
  const chapterCount = Array.isArray(outline?.chapters)
    ? outline!.chapters!.length
    : 0;
  const bookStatus = status; // agent status is the only status we have

  let totalWords = Number(meta.total_words || 0);
  if (!totalWords && meta.chunk_count) {
    totalWords = Number(meta.chunk_count) * WORDS_PER_CHUNK;
  }

  const agentType = (agent.type || "").toLowerCase();
  const isAiBook = agentType === "ai_book";

  // Read: enough body text AND structured enough to read linearly.
  const canRead =
    totalWords >= READ_MIN_WORDS &&
    (chapterCount > 0 ||
      isAiBook ||
      agentType === "upload" ||
      agentType === "url");

  // Preview: something to look at, but not a full read.
  const canPreview =
    (totalWords > 0 && totalWords < READ_MIN_WORDS) ||
    (bookStatus === "writing" && chapterCount > 0);

  // Chat: virtually always available (catalog stubs chat via RAG + LLM).
  const canChat = true;

  return { read: canRead, preview: canPreview, chat: canChat };
}

